/*
 * SlotFakeSpin 的 EffectCraft 後端（tools/sfs.js ec）：沒有 After Effects 時，用 EffectCraft（開源的 AE 相容合成器）
 * 的命令列 effectcraft-cli 在 .ecproj 專案裡建立 / 更新盤面，再輸出檢查畫面和影片。
 *
 * EffectCraft 0.3.1 跟 AE 不同、在這裡處理的地方：
 *  - 不支援 $.evalFile：工作參數（含設定內容）+ dist/SlotFakeSpin_apply.jsx 合併成單一腳本
 *  - 預設不允許腳本寫檔：結果用 writeLn 輸出一行「SFS_RESULT <json>」，從 CLI --json 的 output 讀回；
 *    檢查畫面改用 render-frame 輸出（不呼叫 saveFrameToPng），不去改使用者的偏好設定
 *  - 腳本只能讀 .ecproj 所在資料夾裡的檔案：設定內容直接帶進腳本；素材要在專案資料夾內（或用 --copy-assets 複製進去）
 *  - 腳本出錯時 CLI 一樣會存檔：先另存成暫存檔，成功才取代專案（原檔備份到執行資料夾）
 *  - render 的 --out 相對路徑以 .ecproj 所在資料夾為準：一律傳絕對路徑
 *  - 不理會 ImportOptions.sequence = false：檔名結尾是數字的同系列圖檔（C200.png、C400.png…）會被接成連續圖檔，
 *    這種符號圖複製到 sfs_assets/<名稱>/<檔名>/ 各自的資料夾再匯入
 * 畫線（shape.newPath）、巢狀動態模糊、合成同名自動改名在 src/ae.js 偵測到 EffectCraft 時處理。
 */
"use strict";
const fs = require("fs");
const path = require("path");
const cp = require("child_process");
const S = require("../src/core.js");

const ROOT = path.join(__dirname, "..");
const APPLY_JSX = path.join(ROOT, "dist", "SlotFakeSpin_apply.jsx");
const RESULT_TAG = "SFS_RESULT ";
const ASSET_DIR = "sfs_assets";
const VIDEO_FORMATS = { ".mp4": "h264", ".m4v": "h264", ".mov": "prores", ".webm": "webm", ".gif": "gif" };
// 影片預設算到演出結束後再多一點
const VIDEO_TAIL = 0.6;

const r2 = (v) => Math.round(v * 100) / 100;
const r3 = (v) => Math.round(v * 1000) / 1000;
const pad = (s, n) => { s = String(s); let w = 0; for (const ch of s) w += ch.charCodeAt(0) > 0x2e80 ? 2 : 1; return s + " ".repeat(Math.max(0, n - w)); };

// ---------------------------------------------------------------- CLI
// SFS_EC = effectcraft-cli 的路徑（.js = 測試用的假 CLI，用 node 執行）；沒設定就找預設安裝位置和 PATH
function findEC(env) {
  env = env || process.env;
  if (env.SFS_EC) {
    return /\.js$/i.test(env.SFS_EC) ? { cmd: process.execPath, pre: [env.SFS_EC], label: env.SFS_EC } : { cmd: env.SFS_EC, pre: [], label: env.SFS_EC };
  }
  const exe = process.platform === "win32" ? "effectcraft-cli.exe" : "effectcraft-cli";
  const base = env.LOCALAPPDATA ? path.join(env.LOCALAPPDATA, "Programs", "ArtCraft") : "";
  if (base && fs.existsSync(base)) {
    const dirs = fs.readdirSync(base).filter((d) => /^effectcraft-/i.test(d)).sort(S.util.naturalCompare).reverse();
    for (const d of dirs) {
      const f = path.join(base, d, exe);
      if (fs.existsSync(f)) return { cmd: f, pre: [], label: f };
    }
  }
  const w = cp.spawnSync(process.platform === "win32" ? "where" : "which", ["effectcraft-cli"], { encoding: "utf8" });
  const hit = w.status === 0 ? w.stdout.split(/\r?\n/)[0].trim() : "";
  return hit ? { cmd: hit, pre: [], label: hit } : null;
}

// CLI 的 --json：script / render-frame 只印一行 JSON；render 會先印進度文字，最後一行才是 JSON
function parseCliJson(text) {
  const t = String(text || "").trim();
  if (!t) return null;
  try { return JSON.parse(t); } catch (e) { /* 往下找 */ }
  const lines = t.split(/\r?\n/);
  for (let i = lines.length - 1; i >= 0; i--) {
    if (!/^\s*\{/.test(lines[i])) continue;
    try { return JSON.parse(lines[i]); } catch (e) { /* 下一行 */ }
  }
  return null;
}

function runEC(ec, args, timeoutSec) {
  const r = cp.spawnSync(ec.cmd, ec.pre.concat(args), { encoding: "utf8", maxBuffer: 1 << 28, timeout: timeoutSec * 1000, windowsHide: true });
  const err = r.error ? (r.error.code === "ETIMEDOUT" ? "逾時（" + timeoutSec + " 秒）" : r.error.message) : "";
  return { status: r.status, stdout: r.stdout || "", stderr: r.stderr || "", error: err, json: parseCliJson(r.stdout) };
}

// CLI 回報的錯誤：字串，或 { file, line, column, message }（腳本錯誤）
function describeError(e) {
  if (!e) return "";
  if (typeof e === "string") return e;
  return (e.message || JSON.stringify(e)) + (e.line ? "（" + (e.file || "script") + " line " + e.line + (e.column ? ":" + e.column : "") + "）" : "");
}

// 單次 CLI 呼叫（render-frame / render）的錯誤訊息；成功回傳空字串
function callError(r) {
  if (r.error) return r.error;
  if (r.json && r.json.error) return describeError(r.json.error);
  if (r.status !== 0) return (r.stderr || r.stdout || "exit " + r.status).trim();
  return "";
}

// 從腳本輸出找最後一行 SFS_RESULT
function extractResult(output) {
  const lines = String(output || "").split(/\r?\n/);
  for (let i = lines.length - 1; i >= 0; i--) {
    if (lines[i].indexOf(RESULT_TAG) === 0) return JSON.parse(lines[i].slice(RESULT_TAG.length));
  }
  return null;
}

// ---------------------------------------------------------------- 腳本
function escapeNonAscii(s) {
  return s.replace(/[^\x00-\x7f]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0"));
}

// 工作參數 + 套用腳本合併成單一檔（EffectCraft 不支援 $.evalFile）；全部 ASCII
function makeScript(job, applyCode) {
  return escapeNonAscii("// SlotFakeSpin job for EffectCraft (generated by tools/sfs.js ec) - do not edit\n" +
    "$.global.SFS_APPLY = " + JSON.stringify(job, null, 1) + ";\n") + applyCode;
}

// ---------------------------------------------------------------- 素材
// 設定裡會被匯入的檔案（沒有路徑、只靠專案項目名稱的不算）
function assetRefs(cfg) {
  const refs = [];
  cfg.symbols.forEach((s) => { if (s.path) refs.push({ label: "符號 " + s.name, get: () => s.path, set: (p) => { s.path = p; } }); });
  if (cfg.frame.source === "custom" && cfg.frame.path) {
    refs.push({ label: "繞框素材", get: () => cfg.frame.path, set: (p) => { cfg.frame.path = p; } });
  }
  if (cfg.lineStyle.cellSource === "custom" && cfg.lineStyle.cellPath) {
    refs.push({ label: "中獎格素材", get: () => cfg.lineStyle.cellPath, set: (p) => { cfg.lineStyle.cellPath = p; } });
  }
  return refs;
}

function isInside(dir, file) {
  const r = path.relative(path.resolve(dir), path.resolve(file));
  return !!r && !r.startsWith("..") && !path.isAbsolute(r);
}

function sameFile(a, b) {
  const sa = fs.statSync(a), sb = fs.statSync(b);
  return sa.size === sb.size && fs.readFileSync(a).equals(fs.readFileSync(b));
}

// EffectCraft 0.3.1 不理會 ImportOptions.sequence = false：檔名結尾是數字、同資料夾還有同系列檔案的圖
//（C200.png、C400.png、C1200.png）會被匯入成一段連續圖檔，畫面隨時間換成別張
const endsWithDigits = (file) => /\d$/.test(path.basename(file, path.extname(file)));
function sequenceProne(file) {
  const ext = path.extname(file), m = /^(.*?)\d+$/.exec(path.basename(file, ext));
  if (!m || !fs.existsSync(path.dirname(file))) return false;
  const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const re = new RegExp("^" + esc(m[1]) + "\\d+" + esc(ext) + "$", "i");
  return fs.readdirSync(path.dirname(file)).some((f) => re.test(f) && f.toLowerCase() !== path.basename(file).toLowerCase());
}

// 把素材複製到 <專案資料夾>/sfs_assets/<名稱>/，並改寫設定裡的路徑；回傳 [{ from, to }]
// 檔名結尾是數字的放進各自的資料夾（<名稱>/<檔名>/），EffectCraft 才不會把它們接成連續圖檔
function copyAssets(refs, projDir, name) {
  const base = path.join(projDir, ASSET_DIR, name);
  const done = {}, out = [];
  refs.forEach((ref) => {
    const from = path.resolve(ref.get());
    if (!done[from]) {
      const ext = path.extname(from), stem = path.basename(from, ext);
      const place = (s) => path.join(endsWithDigits(s + ext) ? path.join(base, s) : base, s + ext);
      let to = place(stem);
      for (let n = 2; fs.existsSync(to) && !sameFile(from, to); n++) to = place(stem + "_" + n);
      fs.mkdirSync(path.dirname(to), { recursive: true });
      if (!fs.existsSync(to)) fs.copyFileSync(from, to);
      done[from] = to;
      out.push({ from, to });
    }
    ref.set(done[from]);
  });
  return out;
}

function frameFile(dir, i, label) {
  return path.join(dir, String(i + 1).padStart(2, "0") + "_" + String(label).replace(/[^\w\-]+/g, "_") + ".png");
}

// Hold & Spin 的回合摘要（套用腳本回傳的 result.rounds；sfs.js ae 也用）
function printRounds(res) {
  if (!res.rounds) return;
  console.log("Hold & Spin 回合（格子 = 列-欄）：");
  res.rounds.forEach((rd) => console.log("  " + pad("R" + rd.round, 5) + pad(r2(rd.start).toFixed(2) + "s → " + r2(rd.settle).toFixed(2) + "s", 18) +
    pad("轉 " + rd.cells + " 格", 9) + pad("鎖住 " + (rd.locks.map((l) => l.cell + " " + l.symbol).join("、") || "-"), 30) +
    "剩 " + rd.spinsLeft + (rd.locks.length ? " → " + rd.spinsAfter : "") + (rd.end === "full" ? "　全滿" : rd.end === "out" ? "　用完" : "")));
}

// ---------------------------------------------------------------- 指令
// deps：tools/sfs.js 的 { load, fail }
function cmdEC(file, opt, deps) {
  const { load, fail } = deps;
  const str = (k) => (opt[k] === undefined || opt[k] === true ? "" : String(opt[k]));
  const cfg = load(file);
  const errs = S.validateConfig(cfg);
  if (errs.length) fail("設定有問題，先修正再送進 EffectCraft：\n  " + errs.join("\n  "));
  if (!fs.existsSync(APPLY_JSX)) fail("找不到 " + APPLY_JSX + "，請先 npm run build");

  if (!str("project")) fail("請用 --project 指定 EffectCraft 專案（.ecproj）；檔案不存在時會建立新專案");
  const project = path.resolve(str("project"));
  if (!/\.ecproj$/i.test(project)) fail("--project 要是 .ecproj 檔：" + project);
  const isNew = !fs.existsSync(project);
  const dest = str("save-as") ? path.resolve(str("save-as")) : project;
  if (!/\.ecproj$/i.test(dest)) fail("--save-as 要是 .ecproj 檔：" + dest);
  // EffectCraft 的腳本只能讀開啟的專案所在的資料夾
  const projDir = path.dirname(isNew ? dest : project);

  const mode = str("mode") || "auto";
  if (["auto", "new", "update"].indexOf(mode) < 0) fail("--mode 只能是 auto / new / update");
  if (isNew && str("comp")) fail("新專案裡還沒有合成，不要指定 --comp（會建立新的 SFS_Main 合成）");
  if (isNew && mode === "update") fail("新專案裡沒有盤面可以更新");
  // 沒給 --pos 就用設定檔的 layout.position（例如 from-psd 算好的位置）；兩者都沒有 = 新建時置中、更新時不動
  let position = cfg.layout.position || null;
  if (str("pos")) {
    position = str("pos").split(",").map(Number);
    if (position.length !== 2 || position.some((v) => !isFinite(v))) fail("--pos 格式是 x,y（例如 540,1434）");
  }
  let frames = str("frames") || "auto";
  if (frames !== "auto" && frames !== "none") frames = frames.split(",").map(Number).filter((x) => !isNaN(x));
  let video = "", format = "", range = null;
  if (str("render")) {
    video = path.resolve(str("render"));
    format = str("format") || VIDEO_FORMATS[path.extname(video).toLowerCase()] || "";
    if (!format) fail("不認得影片格式 " + path.extname(video) + "：用 .mp4 / .mov / .webm / .gif，或加 --format h264|hevc|av1|prores|webm|gif");
  }
  if (str("range")) {
    range = str("range").split(",").map(Number);
    if (range.length !== 2 || range.some((v) => !isFinite(v)) || range[1] <= range[0]) fail("--range 格式是 開始秒,結束秒（例如 0,7.4）");
  }
  const timeout = Number(str("timeout") || 300);

  // 送進腳本的設定：路徑都已是絕對路徑；AE 專案的項目 ID 在 EffectCraft 沒有意義
  const run = JSON.parse(JSON.stringify(cfg));
  run.symbols.forEach((s) => { s.itemId = 0; });
  run.frame.itemId = 0;
  run.lineStyle.cellItemId = 0;
  if (isNew) run.layout.target = "new";

  const refs = assetRefs(run);
  const missing = refs.filter((r) => !fs.existsSync(r.get()));
  if (missing.length) fail("找不到素材檔：\n  " + missing.map((r) => r.label + "：" + r.get()).join("\n  "));
  const outside = refs.filter((r) => !isInside(projDir, r.get()));
  const assetName = path.basename(file, path.extname(file));
  if (outside.length && !opt["copy-assets"]) {
    fail("EffectCraft 的腳本只能讀專案資料夾裡的檔案，這些素材在 " + projDir + " 外面：\n  " +
      outside.map((r) => r.label + "：" + r.get()).join("\n  ") +
      "\n請把素材（例如整個符號資料夾）放進專案資料夾，或加上 --copy-assets 自動複製到 " + path.join(projDir, ASSET_DIR, assetName));
  }

  const outDir = path.resolve(str("out") || path.join(path.dirname(path.resolve(file)), ".sfs-run", "ec-" + new Date().toISOString().replace(/[:.]/g, "-")));
  fs.mkdirSync(outDir, { recursive: true });
  if (outside.length && opt["dry-run"]) {
    console.log("（--dry-run：不複製素材，正式執行時會把 " + outside.length + " 個素材複製到 " + path.join(projDir, ASSET_DIR, assetName) + "）");
  } else if (outside.length) {
    const copied = copyAssets(outside, projDir, assetName);
    console.log("已把 " + copied.length + " 個素材複製到 " + path.join(projDir, ASSET_DIR, assetName));
  }
  // 專案資料夾裡會被接成連續圖檔的符號圖：複製到各自的資料夾（不用 --copy-assets 也做，不然畫面會錯）
  const isolate = refs.filter((r) => isInside(projDir, r.get()) && sequenceProne(r.get()));
  if (isolate.length) {
    const what = isolate.map((r) => path.basename(r.get())).join("、");
    if (opt["dry-run"]) {
      console.log("（--dry-run：" + what + " 在 EffectCraft 會被接成連續圖檔，正式執行時會複製到 " + path.join(projDir, ASSET_DIR, assetName) + " 的各自資料夾）");
    } else {
      copyAssets(isolate, projDir, assetName);
      console.log("EffectCraft 會把檔名結尾是數字的同系列圖檔接成連續圖檔：" + what + " 已複製到 " + path.join(projDir, ASSET_DIR, assetName) + " 的各自資料夾");
    }
  }

  const job = {
    config: run, base: path.dirname(path.resolve(file)), mode, comp: str("comp"), board: str("board"),
    frames, position, print: true, result: "", framesDir: "",
  };
  const scriptFile = path.join(outDir, "apply_ec.jsx");
  fs.writeFileSync(scriptFile, makeScript(job, fs.readFileSync(APPLY_JSX, "utf8")));
  // 腳本出錯時 CLI 也會存檔：先存到同資料夾的暫存檔，成功才取代。
  // 新專案先存一個空專案當暫存檔再開啟（--empty 的腳本什麼檔案都不能讀，連 File.exists 都是 false）
  const tmp = path.join(path.dirname(dest), "." + path.basename(dest, path.extname(dest)) + ".sfs-tmp.ecproj");
  const createArgs = ["script", "--eval", "0", "--empty", "--save-as", tmp, "--json"];
  const args = ["script", scriptFile].concat(isNew ? ["--project", tmp, "--save"] : ["--project", project, "--save-as", tmp], ["--json"]);
  const ec = findEC();
  if (opt["dry-run"]) {
    const show = (a) => [ec.cmd].concat(ec.pre, a).map((x) => (/\s/.test(x) ? JSON.stringify(x) : x)).join(" ");
    console.log("工作腳本：" + scriptFile);
    console.log(ec ? "指令：" + (isNew ? show(createArgs) + "\n      " : "") + show(args) : "找不到 EffectCraft（可設定環境變數 SFS_EC）");
    return;
  }
  if (!ec) {
    fail("找不到 EffectCraft 的 effectcraft-cli。請設定環境變數 SFS_EC 為它的完整路徑，例如 " +
      "%LOCALAPPDATA%\\Programs\\ArtCraft\\effectcraft-0.3.1-windows-x64-portable\\effectcraft-cli.exe");
  }

  console.log("送進 EffectCraft：" + ec.label + (isNew ? "（建立新專案）" : ""));
  const removeTmp = () => { try { fs.unlinkSync(tmp); } catch (e) { /* 沒有暫存檔 */ } };
  if (isNew) {
    const r0 = runEC(ec, createArgs, timeout);
    const err0 = callError(r0) || (fs.existsSync(tmp) ? "" : "沒有存出檔案");
    if (err0) { removeTmp(); fail("無法建立新專案（" + tmp + "）：" + err0); }
  }
  const r = runEC(ec, args, timeout);
  fs.writeFileSync(path.join(outDir, "cli.json"), r.stdout);
  if (!r.json) { removeTmp(); fail("EffectCraft 沒有回傳 JSON（" + (r.error || "exit " + r.status) + "）：\n" + (r.stderr || r.stdout)); }
  let res = null;
  try { res = extractResult(r.json.output); } catch (e) { removeTmp(); fail("讀不懂腳本輸出的 SFS_RESULT：" + e.message); }
  if (!r.json.ok) {
    removeTmp();
    fail("EffectCraft 執行腳本失敗（專案沒有修改）：" + describeError(r.json.error) + (res && res.errors.length ? "\n  " + res.errors.join("\n  ") : ""));
  }
  if (!res) { removeTmp(); fail("腳本沒有輸出 SFS_RESULT（專案沒有修改）。輸出：\n" + r.json.output); }
  fs.writeFileSync(path.join(outDir, "result.json"), JSON.stringify(res, null, 2) + "\n");
  if (!res.ok) {
    removeTmp();
    console.log("✗ EffectCraft 回報錯誤（專案沒有修改）：\n  " + res.errors.join("\n  "));
    process.exit(1);
  }
  if (!fs.existsSync(tmp)) fail("EffectCraft 沒有存出專案（" + tmp + "）");
  let backup = "";
  if (fs.existsSync(dest)) {
    backup = path.join(outDir, "before.ecproj");
    fs.copyFileSync(dest, backup);
  }
  fs.renameSync(tmp, dest);

  console.log("✓ " + (res.mode === "update" ? "已更新" : "已建立") + " " + res.board + "（合成 " + res.target +
    (res.position ? "，位置 " + res.position.map(r2).join(",") : "") + "）");
  res.warnings.forEach((w) => console.log("⚠ " + w));
  console.log("全部停妥 " + r2(res.allSettled) + " 秒，演出結束 " + r2(res.endTime) + " 秒");
  console.log("標記：");
  res.markers.forEach((m) => console.log("  " + pad(r2(m.t).toFixed(2) + "s", 8) + pad("f" + m.frame, 7) + m.label));
  printRounds(res);
  console.log("專案：" + dest + (backup ? "（原檔備份：" + backup + "）" : ""));

  const shots = res.shots || [];
  res.frames = [];
  if (shots.length) {
    const dir = path.join(outDir, "frames");
    fs.mkdirSync(dir, { recursive: true });
    console.log("檢查畫面（EffectCraft 實際算圖）：");
    shots.forEach((s, i) => {
      const out = frameFile(dir, i, s.label);
      const rr = runEC(ec, ["render-frame", "--comp", res.target, "--time", String(s.t), "--out", out, "--project", dest, "--json"], timeout);
      const err = callError(rr) || (fs.existsSync(out) ? "" : "沒有輸出檔案");
      res.frames.push({ t: s.t, label: s.label, file: err ? "" : out, error: err || undefined });
      console.log("  " + pad(r2(s.t).toFixed(2) + "s", 8) + pad(s.label, 22) + (err ? "失敗：" + err : out));
    });
  }
  if (video) {
    const start = range ? range[0] : 0;
    const end = range ? range[1] : r3(Math.min(res.targetDuration || Infinity, res.endTime + VIDEO_TAIL));
    fs.mkdirSync(path.dirname(video), { recursive: true });
    const rr = runEC(ec, ["render", "--comp", res.target, "--out", video, "--format", format,
      "--start", String(start), "--end", String(end), "--project", dest, "--json"], Math.max(timeout, 600));
    const err = callError(rr) || (fs.existsSync(video) ? "" : "沒有輸出檔案");
    res.video = { file: err ? "" : video, format, start, end, error: err || undefined };
    console.log(err ? "✗ 影片輸出失敗：" + err : "影片：" + video + "（" + format + "，" + start + "~" + end + " 秒" +
      (res.targetSize ? "，" + res.targetSize.join("×") : "") + "）");
  }
  fs.writeFileSync(path.join(outDir, "result.json"), JSON.stringify(res, null, 2) + "\n");
  console.log("結果：" + path.join(outDir, "result.json"));
  if (res.frames.some((f) => f.error) || (res.video && res.video.error)) process.exit(1);
}

