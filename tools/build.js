#!/usr/bin/env node
/*
 * 把 src/*.js 合併成單一 ExtendScript 檔：dist/SlotFakeSpin.jsx
 *  - 全部包在 IIFE 裡，不污染 AE 的全域
 *  - 移除註解，非 ASCII 字元全部轉成 \uXXXX（不受作業系統語系 / 檔案編碼影響）
 *  - 用 acorn 以 ECMAScript 3 文法檢查（ExtendScript 只支援 ES3）
 */
"use strict";
const fs = require("fs");
const path = require("path");
const acorn = require("acorn");

const ROOT = path.join(__dirname, "..");
// 面板：放進 ScriptUI Panels；套用腳本：給命令列 / agent 自動化用（不建立面板）
const TARGETS = [
  { out: "SlotFakeSpin.jsx", src: ["core.js", "i18n_en.js", "ae.js", "ui.js", "main.js"],
    title: "After Effects slot machine fake-spin panel",
    install: [" * Install: copy this file to  Adobe After Effects <version>/Support Files/Scripts/ScriptUI Panels/",
      " *          restart AE, then open  Window > SlotFakeSpin.jsx"] },
  { out: "SlotFakeSpin_apply.jsx", src: ["core.js", "i18n_en.js", "ae.js", "apply.js"],
    title: "automation entry: build a board from a preset JSON",
    install: [" * Usage: run from File > Scripts > Run Script File (asks for a preset),",
      " *        or let tools/sfs.js launch it via $.global.SFS_APPLY."] },
];

function stripComments(code, file) {
  const comments = [];
  acorn.parse(code, { ecmaVersion: 3, onComment: comments, locations: true, sourceFile: file });
  let out = "";
  let last = 0;
  for (const c of comments) {
    out += code.slice(last, c.start);
    last = c.end;
  }
  out += code.slice(last);
  // 移除只剩空白的行
  return out
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l, i, arr) => l !== "" || (arr[i - 1] !== undefined && arr[i - 1] !== ""))
    .join("\n");
}

function escapeNonAscii(code) {
  let out = "";
  for (const ch of code) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80) { out += ch; continue; }
    if (cp > 0xffff) {
      const hi = Math.floor((cp - 0x10000) / 0x400) + 0xd800;
      const lo = ((cp - 0x10000) % 0x400) + 0xdc00;
      out += "\\u" + hi.toString(16).toUpperCase() + "\\u" + lo.toString(16).toUpperCase();
    } else {
      out += "\\u" + cp.toString(16).toUpperCase().padStart(4, "0");
    }
  }
  return out;
}

function buildOne(target, version) {
  const parts = target.src.map((f) => {
    const code = fs.readFileSync(path.join(ROOT, "src", f), "utf8");
    return "// ---- " + f + " ----\n" + stripComments(code, f).trim() + "\n";
  });
  const header = [
    "/*",
    " * SlotFakeSpin v" + version + " - " + target.title,
  ].concat(target.install, [
    " * Generated by tools/build.js from src/ - do not edit this file directly.",
    " */",
    "",
  ]).join("\n");
  const body = "(function (thisObj) {\n" + parts.join("\n") + "})(this);\n";
  const out = header + escapeNonAscii(body);

  // ES3 文法檢查（會擋下 let/const/箭頭函式、保留字當屬性名、結尾逗號等）
  acorn.parse(out, { ecmaVersion: 3, allowReturnOutsideFunction: false });
  if (/[^\x00-\x7f]/.test(out)) { throw new Error(target.out + " still contains non-ASCII characters"); }

  const file = path.join(ROOT, "dist", target.out);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, out);
  return file;
}

function build() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const core = fs.readFileSync(path.join(ROOT, "src", "core.js"), "utf8");
  const m = /S\.VERSION = "([^"]+)"/.exec(core);
  if (!m || m[1] !== pkg.version) { throw new Error("src/core.js VERSION (" + (m && m[1]) + ") != package.json version (" + pkg.version + ")"); }
  return TARGETS.map((t) => buildOne(t, pkg.version));
}

module.exports = { build };

if (require.main === module) {
  for (const out of build()) {
    console.log("built " + path.relative(ROOT, out) + " (" + fs.statSync(out).size + " bytes)");
  }
}
