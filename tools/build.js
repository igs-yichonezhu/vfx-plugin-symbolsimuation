#!/usr/bin/env node
/*
 * 把 src/*.js 合併成單一 ExtendScript 檔：dist/SlotFakeSpin.jsx
 *  - 全部包在 IIFE 裡，不污染 AE 的全域
 *  - 移除註解，非 ASCII 字元全部轉成 \uXXXX（不受作業系統語系 / 檔案編碼影響）
 *  - 用 acorn 以 ECMAScript 3 文法檢查（ExtendScript 只支援 ES3）
 */
"use strict";
const fs = require("fs");
const path = require("path");
const acorn = require("acorn");

const ROOT = path.join(__dirname, "..");
const SRC = ["core.js", "ae.js", "ui.js", "main.js"];
const OUT = path.join(ROOT, "dist", "SlotFakeSpin.jsx");

function stripComments(code, file) {
  const comments = [];
  acorn.parse(code, { ecmaVersion: 3, onComment: comments, locations: true, sourceFile: file });
  let out = "";
  let last = 0;
  for (const c of comments) {
    out += code.slice(last, c.start);
    last = c.end;
  }
  out += code.slice(last);
  // 移除只剩空白的行
  return out
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l, i, arr) => l !== "" || (arr[i - 1] !== undefined && arr[i - 1] !== ""))
    .join("\n");
}

function escapeNonAscii(code) {
  let out = "";
  for (const ch of code) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80) { out += ch; continue; }
    if (cp > 0xffff) {
      const hi = Math.floor((cp - 0x10000) / 0x400) + 0xd800;
      const lo = ((cp - 0x10000) % 0x400) + 0xdc00;
      out += "\\u" + hi.toString(16).toUpperCase() + "\\u" + lo.toString(16).toUpperCase();
    } else {
      out += "\\u" + cp.toString(16).toUpperCase().padStart(4, "0");
    }
  }
  return out;
}

function build() {
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  const parts = SRC.map((f) => {
    const code = fs.readFileSync(path.join(ROOT, "src", f), "utf8");
    return "// ---- " + f + " ----\n" + stripComments(code, f).trim() + "\n";
  });
  const header = [
    "/*",
    " * SlotFakeSpin v" + pkg.version + " - After Effects slot machine fake-spin tool",
    " * Install: copy this file to  Adobe After Effects <version>/Support Files/Scripts/ScriptUI Panels/",
    " *          restart AE, then open  Window > SlotFakeSpin.jsx",
    " * Generated by tools/build.js from src/ - do not edit this file directly.",
    " */",
    "",
  ].join("\n");
  const body = "(function (thisObj) {\n" + parts.join("\n") + "})(this);\n";
  const out = header + escapeNonAscii(body);

  // ES3 文法檢查（會擋下 let/const/箭頭函式、保留字當屬性名、結尾逗號等）
  acorn.parse(out, { ecmaVersion: 3, allowReturnOutsideFunction: false });
  if (/[^\x00-\x7f]/.test(out)) { throw new Error("dist still contains non-ASCII characters"); }

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  return OUT;
}

module.exports = { build };

if (require.main === module) {
  const out = build();
  console.log("built " + path.relative(ROOT, out) + " (" + fs.statSync(out).size + " bytes)");
}
